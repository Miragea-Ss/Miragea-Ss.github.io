import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'public', 'eliora', 'media-vault', 'index.html');
const source = await readFile(sourcePath, 'utf8');
const baseUrl = 'https://miragea-ss.github.io/eliora/media-vault';

const locales = {
  en: {
    htmlLang: 'en',
    title: 'Miragea — A video portrait of the archive and the work',
    description: 'Enter the films, words, AI production research, GeekSpell series, and working Eliora systems of Miragea / EX_Her.'
  },
  ja: {
    htmlLang: 'ja',
    title: 'Miragea — 映像でたどる作品・サイト・AI制作',
    description: 'Miragea / EX_Her の映像作品、言葉、AI制作、GeekSpell、Elioraの実用システムを映像でたどる案内ページ。'
  },
  zh: {
    htmlLang: 'zh-CN',
    title: 'Miragea — 用影像走进作品、网站与 AI 创作',
    description: '通过影像了解 Miragea / EX_Her 的作品、文字、AI 创作研究、极客魔咒系列与 Eliora 实用系统。'
  }
};

function replaceMeta(html, selector, value) {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return html.replace(new RegExp(`(<meta ${escaped} content=")[^"]*(" \/>)`), `$1${value}$2`);
}

for (const [locale, metadata] of Object.entries(locales)) {
  const canonical = `${baseUrl}/${locale}/`;
  let html = source
    .replace('<html lang="en">', `<html lang="${metadata.htmlLang}">`)
    .replace(/<title>[^<]*<\/title>/, `<title>${metadata.title}</title>`)
    .replace('<link rel="canonical" href="https://miragea-ss.github.io/eliora/media-vault/" />', `<link rel="canonical" href="${canonical}" />`)
    .replace('<meta property="og:url" content="https://miragea-ss.github.io/eliora/media-vault/" />', `<meta property="og:url" content="${canonical}" />`)
    .replace('"@id": "https://miragea-ss.github.io/eliora/media-vault/#page"', `"@id": "${canonical}#page"`)
    .replace('"url": "https://miragea-ss.github.io/eliora/media-vault/",\n          "inLanguage": ["en", "ja", "zh"]', `"url": "${canonical}",\n          "inLanguage": "${locale}"`)
    .replace('href="../../favicon.svg"', 'href="../../../favicon.svg"')
    .replaceAll('href="./styles.css', 'href="../styles.css')
    .replaceAll('src="./app.js', 'src="../app.js')
    .replaceAll('src="../../assets/', 'src="../../../assets/')
    .replaceAll('src="../../eliora/assets/', 'src="../../../eliora/assets/')
    .replace('<script type="application/ld+json">', `<script>window.__MEDIA_VAULT_LANG__ = "${locale}";</script>\n  <script type="application/ld+json">`)
    .replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/generate-media-vault-locales.mjs; edit ../index.html instead. -->');

  html = replaceMeta(html, 'name="description"', metadata.description);
  html = replaceMeta(html, 'property="og:title"', metadata.title);
  html = replaceMeta(html, 'property="og:description"', metadata.description);
  html = replaceMeta(html, 'name="twitter:title"', metadata.title);
  html = replaceMeta(html, 'name="twitter:description"', metadata.description);

  const outputDir = path.join(root, 'public', 'eliora', 'media-vault', locale);
  await mkdir(outputDir, { recursive: true });
  await writeFile(path.join(outputDir, 'index.html'), html, 'utf8');
  console.log(`Generated Media Vault locale: ${locale}`);
}
